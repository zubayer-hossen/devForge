import { api } from './client';

const get = (url, params) => api.get(url, { params }).then((r) => r.data.data);
const mutate = (method, url, data) => api({ method, url, data }).then((r) => r.data); // { message, data }

export const adminApi = {
  stats: () => get('/admin/stats'),
  counts: () => get('/admin/counts'),
  applications: (params) => get('/admin/applications', params),
  decide: (id, body) => mutate('post', `/admin/applications/${id}/decision`, body),
  members: (params) => get('/admin/members', params),
  member: (id) => get(`/admin/members/${id}`),
  updateMember: (id, body) => mutate('patch', `/admin/members/${id}`, body),
  suspend: (id, body) => mutate('post', `/admin/members/${id}/suspend`, body),
  reactivate: (id) => mutate('post', `/admin/members/${id}/reactivate`),
  changeRole: (id, body) => mutate('patch', `/admin/members/${id}/role`, body),
  removeMember: (id) => mutate('delete', `/admin/members/${id}`),
  pointLedger: (id) => get(`/admin/members/${id}/points`),
  adjustPoints: (id, body) => mutate('post', `/admin/members/${id}/points`, body),
  activity: (params) => get('/admin/activity', params),
  emailLogs: (params) => get('/admin/email/logs', params),
  testEmail: (body) => mutate('post', '/admin/email/test', body),
  settings: () => get('/admin/settings'),
  saveSettings: (body) => mutate('patch', '/admin/settings', body),
  uploadLogo: (file) => { const f = new FormData(); f.append('logo', file); return mutate('post', '/admin/settings/logo', f); },
  removeLogo: () => mutate('delete', '/admin/settings/logo'),
  tasks: (params) => get('/admin/tasks', params),
  task: (id) => get(`/admin/tasks/${id}`),
  createTask: (body) => mutate('post', '/admin/tasks', body),
  updateTask: (id, body) => mutate('put', `/admin/tasks/${id}`, body),
  deleteTask: (id) => mutate('delete', `/admin/tasks/${id}`),
  publishTask: (id) => mutate('post', `/admin/tasks/${id}/publish`),
  unpublishTask: (id) => mutate('post', `/admin/tasks/${id}/unpublish`),
  closeTask: (id) => mutate('post', `/admin/tasks/${id}/close`),
  reopenTask: (id, body = {}) => mutate('post', `/admin/tasks/${id}/reopen`, body),
  uploadAttachment: (id, file) => { const f = new FormData(); f.append('file', file); return mutate('post', `/admin/tasks/${id}/attachments`, f); },
  removeAttachment: (id, publicId) => api.delete(`/admin/tasks/${id}/attachments`, { params: { publicId } }).then((r) => r.data),
  submissions: (params) => get('/admin/submissions', params),
  submission: (id) => get(`/admin/submissions/${id}`),
  startReview: (id) => mutate('post', `/admin/submissions/${id}/start-review`),
  reviewSubmission: (id, body) => mutate('post', `/admin/submissions/${id}/review`, body),
  createResource: (formData) => mutate('post', '/admin/resources', formData),
  updateResource: (id, formData) => mutate('put', `/admin/resources/${id}`, formData),
  deleteResource: (id) => mutate('delete', `/admin/resources/${id}`),
  announcements: (params) => get('/admin/announcements', params),
  createAnnouncement: (body) => mutate('post', '/admin/announcements', body),
  updateAnnouncement: (id, body) => mutate('put', `/admin/announcements/${id}`, body),
  deleteAnnouncement: (id) => mutate('delete', `/admin/announcements/${id}`),
  publishAnnouncement: (id) => mutate('post', `/admin/announcements/${id}/publish`),
  scheduleAnnouncement: (id, body) => mutate('post', `/admin/announcements/${id}/schedule`, body),
  unscheduleAnnouncement: (id) => mutate('post', `/admin/announcements/${id}/unschedule`),
  unpublishAnnouncement: (id) => mutate('post', `/admin/announcements/${id}/unpublish`),
  groups: () => get('/admin/groups'),
  group: (id) => get(`/admin/groups/${id}`),
  createGroup: (body) => mutate('post', '/admin/groups', body),
  updateGroup: (id, body) => mutate('patch', `/admin/groups/${id}`, body),
  deleteGroup: (id) => mutate('delete', `/admin/groups/${id}`),
  addGroupMembers: (id, body) => mutate('post', `/admin/groups/${id}/members`, body),
  removeGroupMember: (id, userId) => mutate('delete', `/admin/groups/${id}/members/${userId}`),
};
